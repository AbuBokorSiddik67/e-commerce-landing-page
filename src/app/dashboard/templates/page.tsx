import { prisma } from "@/lib/prisma";
import { Card, PageHeader } from "@/components/ui";
import { TEMPLATES, SECTION_LABELS } from "@/lib/page-sections";

export default async function TemplatesPage() {
  const templates = await prisma.landingPageTemplate.findMany({ where: { isActive: true }, orderBy: { name: "asc" } });
  return (
    <>
      <PageHeader title="Templates" description="Editable starting points. Applying a template replaces the current sections of a page; save or publish afterwards." />
      <div className="grid gap-5 md:grid-cols-2 xl:grid-cols-3">
        {templates.map((template) => {
          const definition = TEMPLATES.find((t) => t.code === template.code);
          const sections = (template.sections as Array<{ type: string }>) ?? definition?.sections ?? [];
          return <Card key={template.id} className="overflow-hidden"><div className="h-24" style={{ background: `linear-gradient(135deg, ${template.previewColor}, #0d121c)` }} /><div className="p-5"><div className="flex items-center justify-between"><h2 className="font-semibold">{template.name}</h2><span className="badge bg-ink-100 text-ink-600">{template.category}</span></div><p className="mt-2 text-sm text-ink-500">{template.description ?? definition?.description}</p><p className="mt-4 text-xs text-ink-400">{sections.length} sections: {sections.slice(0, 5).map((s) => SECTION_LABELS[s.type as keyof typeof SECTION_LABELS] ?? s.type).join(" · ")}…</p></div></Card>;
        })}
      </div>
      <p className="mt-6 text-xs text-ink-400">Templates are stored as structured JSON, not executable code. No customer data or reviews are generated by templates.</p>
    </>
  );
}
